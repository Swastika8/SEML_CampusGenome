export const campusPlaces = places.map(
  ([id, name, category, shape, cx, cy, labelX, labelY, anchor, lines], order) => ({
    id,
    name,
    category,
    description:
      'Marked on the campus plan shared by the CampusGenome community. Add a field note to share useful local knowledge.',
    map_data: {
      shape,
      cx,
      cy,
      labelX,
      labelY,
      anchor,
      lines,
      order,
      source: 'owner-supplied-plan',
    },
  }),
);

export async function applyCampusMap(client) {
  await client.query(
    `INSERT INTO buildings (id,name,description,category,map_data)
     SELECT id,name,description,category,map_data
     FROM jsonb_to_recordset($1::jsonb)
       AS p(id text,name text,description text,category text,map_data jsonb)
     ON CONFLICT (id) DO UPDATE SET map_data=EXCLUDED.map_data`,
    [JSON.stringify(campusPlaces)],
  );
}
